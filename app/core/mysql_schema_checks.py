"""Fail-closed validation of partial MySQL DDL before version advancement."""
import re
from sqlalchemy import inspect, CheckConstraint, UniqueConstraint

def canonical(expression):
    # These frozen checks use only IN lists and >=; parentheses do not change
    # their meaning. Preserve string-literal case/content.
    tokens = re.findall(r"'(?:''|[^'])*'|`[^`]*`|[A-Za-z_0-9]+|>=|[^\s]", str(expression))
    return tuple(t if t.startswith("'") else t.strip('`').lower() for t in tokens if t not in ('(', ')', '_utf8mb4'))

def validate_table(conn, table):
    inspector = inspect(conn)
    actual = inspector.get_columns(table.name)
    expected = list(table.columns)
    def type_name(kind):
        return re.sub(r" (?:CHARACTER SET|COLLATE) [^ ]+", "", str(kind.compile(dialect=conn.dialect)), flags=re.I).lower()
    def default(value):
        if value is None:
            return None
        return str(value).strip("'")
    wanted = [(c.name, type_name(c.type), c.nullable, default(c.server_default.arg) if c.server_default else None) for c in expected]
    observed = [(c['name'], type_name(c['type']), c['nullable'], default(c['default'])) for c in actual]
    unique = {tuple(c.columns.keys()) for c in table.constraints if isinstance(c, UniqueConstraint)}
    seen_unique = {tuple(c['column_names']) for c in inspector.get_unique_constraints(table.name)}
    def action(value):
        normalized = str(value or "").upper()
        return "" if normalized in ("", "RESTRICT", "NO ACTION") else normalized
    foreign = {(tuple(fk.parent.name for fk in constraint.elements), tuple(fk.target_fullname for fk in constraint.elements), action(constraint.ondelete), action(constraint.onupdate)) for constraint in table.foreign_key_constraints}
    seen_foreign = {(tuple(f['constrained_columns']), tuple(f["referred_table"]+'.'+c for c in f['referred_columns']), action(f.get('options', {}).get('ondelete')), action(f.get('options', {}).get('onupdate'))) for f in inspector.get_foreign_keys(table.name)}
    wrong_foreign_schema = any(f.get('referred_schema') not in (None, conn.engine.url.database) for f in inspector.get_foreign_keys(table.name))
    checks = {canonical(c.sqltext) for c in table.constraints if isinstance(c, CheckConstraint)}
    seen_checks = {canonical(c['sqltext']) for c in inspector.get_check_constraints(table.name)}
    options = inspector.get_table_options(table.name)
    # FK supporting indexes are generated by MySQL, but unrelated indexes
    # change the accepted object and cannot be silently stamped.
    allowed_indexes = {(c.name, tuple(c.columns.keys()), True) for c in table.constraints if isinstance(c, UniqueConstraint)}
    allowed_indexes |= {(con.elements[0].parent.name, tuple(fk.parent.name for fk in con.elements), False) for con in table.foreign_key_constraints}
    allowed_indexes |= {(index.name, tuple(column.name for column in index.columns), bool(index.unique)) for index in table.indexes}
    indexes = inspector.get_indexes(table.name)
    # Explicit baseline indexes must exist with the frozen name, column order,
    # and uniqueness. MySQL may add FK-supporting indexes implicitly, so those
    # remain allowed above without becoming required baseline indexes here.
    expected_indexes = {
        (index.name, tuple(column.name for column in index.columns), bool(index.unique))
        for index in table.indexes
    }
    observed_indexes = {
        (index['name'], tuple(index['column_names']), bool(index['unique']))
        for index in indexes
    }
    missing_indexes = expected_indexes - observed_indexes
    unexpected_indexes = [i for i in indexes if (i['name'], tuple(i['column_names']), bool(i['unique'])) not in allowed_indexes or i.get('column_sorting') or i.get('dialect_options')]
    wrong_encoding = any(getattr(c['type'], 'collation', None) not in (None, 'utf8mb4_0900_bin') or getattr(c['type'], 'charset', None) not in (None, 'utf8mb4') for c in actual)
    disabled_checks = conn.exec_driver_sql(
        "SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE() AND TABLE_NAME=%s AND CONSTRAINT_TYPE='CHECK' AND ENFORCED='NO'", (table.name,)).scalar_one()
    if (wanted != observed or inspector.get_pk_constraint(table.name)['constrained_columns'] != list(table.primary_key.columns.keys())
        or unique != seen_unique or foreign != seen_foreign or checks != seen_checks
        or missing_indexes or unexpected_indexes
        or wrong_encoding or wrong_foreign_schema or disabled_checks
        or options.get('mysql_engine') != 'InnoDB'
        or options.get('mysql_collate') != 'utf8mb4_0900_bin'
        or options.get('mysql_default charset') != 'utf8mb4'):
        raise RuntimeError('MySQL schema differs from frozen identity baseline: '+table.name)

def validate_existing(conn, metadata):
    inspector = inspect(conn)
    actual = set(inspector.get_table_names())
    if actual - set(metadata.tables) - {'alembic_version'} or inspector.get_view_names():
        raise RuntimeError('MySQL schema differs: untracked schema objects')
    triggers = conn.exec_driver_sql('SELECT COUNT(*) FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE()').scalar_one()
    if triggers:
        raise RuntimeError('MySQL schema differs: untracked triggers')
    for name in actual & set(metadata.tables):
        validate_table(conn, metadata.tables[name])
